/**
 * Build a Microsoft Sentinel scheduled analytics rule YAML stub
 * suitable for detection-as-code repos (ARM/Bicep/YAML pipelines).
 */
export function buildAnalyticsRuleYaml(
    documentText: string,
    rule: RuleMetadata,
    options: AnalyticsRuleYamlOptions = {}
): string {
    const query = getRuleQueryText(documentText, rule);
    const id = options.id ?? stableRuleId(rule.title);
    const severity = rule.severity ?? 'Medium';
    const description = rule.description ?? rule.title;
    const queryFrequency = rule.queryFrequency ?? '1h';
    const queryPeriod = rule.queryPeriod ?? queryFrequency;
    const triggerOperator = rule.triggerOperator ?? 'gt';
    const triggerThreshold = rule.triggerThreshold ?? '0';
    const kind = rule.kind ?? 'Scheduled';

    const tactics = rule.tactics.length > 0 ? rule.tactics : [];
    const techniques = rule.techniques;
    const connectors = inferDataConnectors(query);
    const mappings = inferEntityMappings(query);

    const lines: string[] = [
        `# Generated by KQL Assistant — review before deploying to Sentinel`,
        `id: ${id}`,
        `name: ${yamlScalar(rule.title)}`,
        `description: |`,
        ...description.split('\n').map(line => `  ${line}`),
        `severity: ${severity}`,
        `requiredDataConnectors:`
    ];

    if (connectors.length === 0) {
        lines.push('  []');
    } else {
        for (const connector of connectors) {
            lines.push(`  - connectorId: ${connector.connectorId}`);
            lines.push(`    dataTypes:`);
            for (const dataType of connector.dataTypes) {
                lines.push(`      - ${dataType}`);
            }
        }
    }

    lines.push(`queryFrequency: ${queryFrequency}`);
    lines.push(`queryPeriod: ${queryPeriod}`);
    lines.push(`triggerOperator: ${triggerOperator}`);
    lines.push(`triggerThreshold: ${triggerThreshold}`);
    lines.push(`status: Available`);
    lines.push(`tactics:`);

    if (tactics.length === 0) {
        lines.push('  []');
    } else {
        for (const tactic of tactics) {
            lines.push(`  - ${tacticDisplayName(tactic)}`);
        }
    }

    lines.push('relevantTechniques:');
    if (techniques.length === 0) {
        lines.push('  []');
    } else {
        for (const technique of techniques) {
            lines.push(`  - ${technique}`);
        }
    }

    lines.push('query: |');
    if (query.trim() === '') {
        lines.push('  # (empty query)');
    } else {
        for (const line of query.split('\n')) {
            lines.push(`  ${line}`);
        }
    }

    lines.push('entityMappings:');
    if (mappings.length === 0) {
        lines.push('  []');
    } else {
        for (const mapping of mappings) {
            lines.push(`  - entityType: ${mapping.entityType}`);
            lines.push(`    fieldMappings:`);
            for (const field of mapping.fieldMappings) {
                lines.push(`      - identifier: ${field.identifier}`);
                lines.push(`        columnName: ${field.columnName}`);
            }
        }
    }

    lines.push('version: 1.0.0');
    lines.push(`kind: ${kind}`);
    lines.push('');

    return lines.join('\n');
}

export function inferEntityMappings(query: string): EntityMapping[] {
    const columns = collectOutputColumns(query);
    const grouped = new Map<string, EntityFieldMapping[]>();

    for (const column of columns) {
        const match = COLUMN_ENTITIES.find(entry => entry.pattern.test(column));
        if (!match) {
            continue;
        }
        const fields = grouped.get(match.entityType) ?? [];
        if (!fields.some(field => field.columnName.toLowerCase() === column.toLowerCase())) {
            fields.push({ identifier: match.identifier, columnName: column });
        }
        grouped.set(match.entityType, fields);
    }

    return [...grouped.entries()].map(([entityType, fieldMappings]) => ({
        entityType,
        fieldMappings
    }));
}

export function inferDataConnectors(query: string): RequiredDataConnector[] {
    const tables = collectSourceTables(query);
    const byId = new Map<string, Set<string>>();

    for (const table of tables) {
        const connector = TABLE_CONNECTORS[table];
        if (!connector) {
            continue;
        }
        const dataTypes = byId.get(connector.connectorId) ?? new Set<string>();
        for (const dataType of connector.dataTypes) {
            dataTypes.add(dataType);
        }
        byId.set(connector.connectorId, dataTypes);
    }

    return [...byId.entries()].map(([connectorId, dataTypes]) => ({
        connectorId,
        dataTypes: [...dataTypes]
    }));
}

function collectSourceTables(query: string): string[] {
    const model = buildQueryModel(query);
    const tables: string[] = [];
    for (const block of model.blocks) {
        if (block.sourceTable) {
            tables.push(block.sourceTable);
        }
        for (const step of block.steps) {
            tables.push(...step.outputTables);
            tables.push(...step.inputTables);
            if (step.join?.rightTable) {
                tables.push(step.join.rightTable);
            }
        }
    }
    return unique(tables);
}

function collectOutputColumns(query: string): string[] {
    const model = buildQueryModel(query);
    const block = model.blocks[model.blocks.length - 1];
    if (!block) {
        return [];
    }
    const lastProject = [...block.steps]
        .reverse()
        .find(step => step.operator === 'project' || step.operator === 'project-keep');
    if (lastProject) {
        return lastProject.outputColumns;
    }
    const last = block.steps[block.steps.length - 1];
    if (last) {
        return last.outputColumns;
    }
    return block.sourceColumns ?? [];
}

function unique(values: string[]): string[] {
    const seen = new Set<string>();
    const result: string[] = [];
    for (const value of values) {
        if (!seen.has(value)) {
            seen.add(value);
            result.push(value);
        }
    }
    return result;
}

function yamlScalar(value: string): string {
    if (/[:#{}[\],&*?|>!%@`]/.test(value) || value.includes("'") || value.includes('"')) {
        return JSON.stringify(value);
    }
    return value;
}

function stableRuleId(title: string): string {
    const hash = createHash('sha1').update(title).digest('hex');
    return [
        hash.slice(0, 8),
        hash.slice(8, 12),
        '4' + hash.slice(13, 16),
        ((parseInt(hash.slice(16, 18), 16) & 0x3f) | 0x80).toString(16).padStart(2, '0') +
            hash.slice(18, 20),
        hash.slice(20, 32)
    ].join('-');
}
